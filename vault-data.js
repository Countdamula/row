  function list(shelf) { return storeGet(keyFor(shelf)) || []; }
  function replaceAll(shelf, arr) { return storeSet(keyFor(shelf), arr || []); }

  function add(shelf, fields) {
    var all = list(shelf);
    var item = Object.assign({
      id: 'v_' + Date.now().toString(36) + '_' + Math.random().toString(36).slice(2, 8),
      title: '', url: '', cover: '', creator: '', description: '', category: '',
      lengthText: '', notes: '', rating: 0, favorite: false, queued: false,
      openCount: 0, lastOpenedAt: null, source: '', importedFrom: '', legacyId: '',
      createdAt: Date.now(), updatedAt: Date.now(),
    }, fields || {});
    item.order = all.length;
    all.push(item);
    replaceAll(shelf, all);
    return item;
  }

  function update(shelf, id, patch) {
    var all = list(shelf);
    var i = all.findIndex(function (x) { return x.id === id; });
    if (i < 0) return null;
    all[i] = Object.assign({}, all[i], patch, { updatedAt: Date.now() });
    replaceAll(shelf, all);
    return all[i];
  }

  /** Stamped on every card open — powers Continue and the activity stats. */
  function touch(shelf, id) {
    var it = list(shelf).find(function (x) { return x.id === id; });
    if (!it) return;
    update(shelf, id, { lastOpenedAt: Date.now(), openCount: (it.openCount || 0) + 1 });
  }

  function counts() {
    var out = {};
    SHELVES.forEach(function (s) { out[s] = list(s).length; });
    return out;
  }

  // ============================================================
  // SEEDING — additive only, and it never deletes.
  //
  // A shelf is seeded only when it is EMPTY. Anything already there wins,
  // so a re-run can't clobber edits, and an item deleted deliberately in
  // the Vault does not come back on the next load.
  //
  // Merge is by canonical URL rather than id, matching the migration: the
  // same link stored with a different tracking parameter is one item.
  // ============================================================
  function canonUrl(raw) {
    if (!raw) return '';
    try {
      var u = new URL(String(raw).trim());
      var host = u.hostname.replace(/^www\./, '').toLowerCase();
      var keep = new URLSearchParams();
      if (/youtube\.com|youtu\.be/.test(host)) {
        ['v', 'list'].forEach(function (p) { if (u.searchParams.has(p)) keep.set(p, u.searchParams.get(p)); });
      }
      var qs = keep.toString();
      return host + u.pathname.replace(/\/+$/, '') + (qs ? '?' + qs : '');
    } catch (e) { return String(raw).trim().toLowerCase(); }
  }

  function seedShelf(shelf) {
    var incoming = SEED[shelf] || [];
    if (!incoming.length) return 0;
    var existing = list(shelf);
    var have = {};
    existing.forEach(function (x) { var c = canonUrl(x.url); if (c) have[c] = true; });
    var added = incoming.filter(function (x) { var c = canonUrl(x.url); return !c || !have[c]; });
    if (!added.length) return 0;
    replaceAll(shelf, existing.concat(added.map(function (x, i) {
      return Object.assign({}, x, { order: existing.length + i });
    })));
    return added.length;
  }

  function seedNow() {
    var total = 0;
    Object.keys(SEED).forEach(function (s) { total += seedShelf(s); });
    if (total) storeSet('vault:seededAt', Date.now());
    return total;
  }

  /**
   * Race safety, same shape as every other page here. On a fresh device the
   * initial Supabase pull is still in flight at load time; seeding straight
   * away would write the seed locally and push it, duplicating whatever the
   * remote row already held. So: seed immediately only if a remote apply has
   * already happened, otherwise wait one beat for the pull, then seed only
   * what is still missing.
   */
  function maybeSeedAfterSyncAttempt(ref, onDone) {
    var run = function () {
      var n = seedNow();
      if (n && typeof onDone === 'function') onDone(n);
    };
    if (ref && ref.applied) { run(); return; }
    setTimeout(run, 1200);
  }

